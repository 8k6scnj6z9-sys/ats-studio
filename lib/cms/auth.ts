import "server-only";
import { createHash, createHmac, scryptSync, timingSafeEqual } from "node:crypto";
import { cookies, headers } from "next/headers";
import { redirect } from "next/navigation";
import { checkRateLimit } from "@/lib/security/rate-limit";

const COOKIE = "ats_admin";
const SESSION_SECONDS = 8 * 60 * 60;

function config() {
  const passwordHash = process.env.ADMIN_PASSWORD_HASH ?? "";
  const secret = process.env.ADMIN_SESSION_SECRET ?? "";
  if (!passwordHash.startsWith("scrypt:") || secret.length < 32) return null;
  return { passwordHash, secret };
}

function eq(a: Buffer, b: Buffer) {
  return a.length === b.length && timingSafeEqual(a, b);
}

/** Format: scrypt:<salt hex>:<hash hex>, generated by scripts/hash-admin-password.mjs. */
export function verifyPassword(password: string, stored: string) {
  const [, salt, hash] = stored.split(":");
  if (!salt || !hash) return false;
  return eq(scryptSync(password, Buffer.from(salt, "hex"), 64), Buffer.from(hash, "hex"));
}

// Changing the password or the secret invalidates every open session.
function sign(expires: number, { passwordHash, secret }: { passwordHash: string; secret: string }) {
  const passwordTag = createHash("sha256").update(passwordHash).digest("hex");
  return createHmac("sha256", secret).update(`admin.${expires}.${passwordTag}`).digest("base64url");
}

export async function isAdmin() {
  const cfg = config();
  const token = (await cookies()).get(COOKIE)?.value;
  if (!cfg || !token) return false;
  const [expires, signature] = token.split(".");
  const exp = Number(expires);
  if (!Number.isFinite(exp) || exp < Date.now() || !signature) return false;
  return eq(Buffer.from(signature), Buffer.from(sign(exp, cfg)));
}

export async function requireAdmin() {
  if (!(await isAdmin())) redirect("/admin/login");
}

export type LoginResult = { error?: "invalid" | "limited" | "not_configured" };

export async function login(password: string): Promise<LoginResult> {
  const cfg = config();
  if (!cfg) return { error: "not_configured" };
  const request = new Request("http://admin.local", { headers: await headers() });
  if (checkRateLimit(request, "admin-login", { windowMs: 15 * 60 * 1000, max: 5 }).limited) {
    return { error: "limited" };
  }
  if (!verifyPassword(password, cfg.passwordHash)) return { error: "invalid" };

  const expires = Date.now() + SESSION_SECONDS * 1000;
  (await cookies()).set(COOKIE, `${expires}.${sign(expires, cfg)}`, {
    httpOnly: true,
    secure: process.env.NODE_ENV === "production",
    sameSite: "strict",
    path: "/",
    maxAge: SESSION_SECONDS,
  });
  return {};
}

export async function logout() {
  (await cookies()).delete(COOKIE);
}
